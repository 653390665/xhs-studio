from __future__ import annotations

from datetime import datetime
from typing import Optional

from sqlalchemy import DateTime, ForeignKey, Index, Integer, JSON, String, Text
from sqlalchemy.orm import Mapped, mapped_column

from backend.app.core.database import Base
from backend.app.core.time import shanghai_now


class AccountPositioning(Base):
    """The account's positioning: who it serves and what it will never write.

    Deliberately **not** a style profile. Early-stage accounts do not have a
    style yet (a style needs a corpus to be distilled from), but they always
    need a positioning: without it every generated draft drifts, and without a
    taboos list the model happily writes things the owner would never say.

    Only six fields are stored. Everything else that the persona Skills produce
    has a home elsewhere: visual identity belongs to the visual skills, content
    pipeline to the schedule, channel assets to the topic bank. Keeping this
    table small is what makes it usable in a prompt budget.
    """

    __tablename__ = "account_positioning"
    __table_args__ = (
        Index("uq_account_positioning_account", "platform_account_id", unique=True),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    user_id: Mapped[int] = mapped_column(ForeignKey("users.id"), index=True)
    platform_account_id: Mapped[int] = mapped_column(
        ForeignKey("platform_accounts.id"), index=True
    )

    # 变现倒推定位 step 6:「我帮谁，在什么场景下，解决什么问题，为什么是我」
    positioning: Mapped[str] = mapped_column(Text, default="")
    audience: Mapped[str] = mapped_column(Text, default="")
    promise: Mapped[str] = mapped_column(Text, default="")

    # 账号档案 step 5 / 话题方向；JSON arrays of short strings.
    main_topics: Mapped[Optional[list]] = mapped_column(JSON, nullable=True)
    taboos: Mapped[Optional[list]] = mapped_column(JSON, nullable=True)

    # 账号档案 step 3: 5-10 句真实原话. Raw material, not a distilled style.
    language_samples: Mapped[Optional[list]] = mapped_column(JSON, nullable=True)

    # Where each field came from: "manual" / "skill:<slug>". Lets a reader tell
    # a user-typed positioning from one generated by a Skill run.
    source: Mapped[str] = mapped_column(String(128), default="manual")

    created_at: Mapped[datetime] = mapped_column(DateTime, default=shanghai_now)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime, default=shanghai_now, onupdate=shanghai_now
    )
